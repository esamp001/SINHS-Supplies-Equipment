import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';

import { SCHOOL } from './constants.js';
import { formatManilaDateTime } from './dates.js';

/**
 * Turns a report (built by reports.service.js) into an Excel or PDF file (AGENTS.md §5).
 * Every export starts with the school name, report title, filters used, who generated it and
 * when (Asia/Manila).
 */

/**
 * @typedef {Object} ReportColumn
 * @property {string} key - Row property to print.
 * @property {string} label - Column heading.
 * @property {number} width - Relative width (Excel characters; scaled for PDF).
 */

/**
 * @typedef {Object} Report
 * @property {string} key - Report key, e.g. "stock-levels".
 * @property {string} title - Report title.
 * @property {string[]} filters - Human-readable filter lines.
 * @property {ReportColumn[]} columns - Columns.
 * @property {Array<Object<string, string | number>>} rows - Display-ready rows.
 * @property {string} generatedBy - Name of the user who generated it.
 * @property {string} generatedAt - ISO timestamp.
 */

/** Header color used in both formats. */
const HEADER_FILL = '1F4FA8';

/**
 * Lines printed above the table in every export.
 * @param {Report} report - Report.
 * @returns {string[]} Heading lines after the school name and title.
 */
const getInfoLines = (report) => [
  `Filters: ${report.filters.length ? report.filters.join('; ') : 'None'}`,
  `Generated by ${report.generatedBy} on ${formatManilaDateTime(report.generatedAt)} (Asia/Manila)`,
];

/**
 * Builds an Excel workbook for a report.
 * @param {Report} report - Report.
 * @returns {Promise<Buffer>} .xlsx file contents.
 */
export const buildExcel = async (report) => {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet(report.title.slice(0, 31));
  const lastColumn = report.columns.length;

  workbook.creator = SCHOOL.systemName;
  workbook.created = new Date(report.generatedAt);

  const headingLines = [
    { text: SCHOOL.name, font: { bold: true, size: 14 } },
    { text: report.title, font: { bold: true, size: 12 } },
    ...getInfoLines(report).map((text) => ({ text, font: { size: 10, italic: true } })),
  ];

  headingLines.forEach((line, index) => {
    const rowNumber = index + 1;

    sheet.mergeCells(rowNumber, 1, rowNumber, lastColumn);
    sheet.getCell(rowNumber, 1).value = line.text;
    sheet.getCell(rowNumber, 1).font = line.font;
  });

  const headerRowNumber = headingLines.length + 2;
  const headerRow = sheet.getRow(headerRowNumber);

  report.columns.forEach((column, index) => {
    const cell = headerRow.getCell(index + 1);

    cell.value = column.label;
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${HEADER_FILL}` } };
    sheet.getColumn(index + 1).width = column.width;
  });

  report.rows.forEach((row) => {
    sheet.addRow(report.columns.map((column) => row[column.key] ?? ''));
  });

  if (!report.rows.length) {
    sheet.addRow(['No records match these filters.']);
  }

  sheet.views = [{ state: 'frozen', ySplit: headerRowNumber }];

  return Buffer.from(await workbook.xlsx.writeBuffer());
};

/**
 * Draws the table header row on the current PDF page.
 * @param {PDFKit.PDFDocument} doc - PDF document.
 * @param {ReportColumn[]} columns - Columns.
 * @param {number[]} widths - Column widths in points.
 * @param {number} y - Top of the row.
 * @returns {number} Height of the header row.
 */
const drawPdfHeader = (doc, columns, widths, y) => {
  const height = 20;
  const left = doc.page.margins.left;
  const totalWidth = widths.reduce((sum, width) => sum + width, 0);

  doc.rect(left, y, totalWidth, height).fill(`#${HEADER_FILL}`);
  doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(8);

  let x = left;

  columns.forEach((column, index) => {
    doc.text(column.label, x + 4, y + 6, { width: widths[index] - 8, lineBreak: false });
    x += widths[index];
  });

  doc.fillColor('#000000').font('Helvetica');

  return height;
};

/**
 * Builds a landscape A4 PDF for a report, repeating the table header on every page.
 * @param {Report} report - Report.
 * @returns {Promise<Buffer>} .pdf file contents.
 */
export const buildPdf = (report) =>
  new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 36 });
    const chunks = [];

    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const usableWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;
    const totalUnits = report.columns.reduce((sum, column) => sum + column.width, 0);
    const widths = report.columns.map((column) => (column.width / totalUnits) * usableWidth);
    const bottom = doc.page.height - doc.page.margins.bottom;

    doc.font('Helvetica-Bold').fontSize(14).text(SCHOOL.name);
    doc.fontSize(12).text(report.title);
    doc.font('Helvetica-Oblique').fontSize(9);
    getInfoLines(report).forEach((line) => doc.text(line));
    doc.moveDown(0.8);

    let y = doc.y;

    y += drawPdfHeader(doc, report.columns, widths, y);
    doc.fontSize(8);

    if (!report.rows.length) {
      doc.text('No records match these filters.', doc.page.margins.left, y + 6);
    }

    report.rows.forEach((row, rowIndex) => {
      const values = report.columns.map((column) => String(row[column.key] ?? ''));

      const rowHeight =
        Math.max(
          ...values.map((value, index) => doc.heightOfString(value, { width: widths[index] - 8 })),
        ) + 8;

      if (y + rowHeight > bottom) {
        doc.addPage();
        y = doc.page.margins.top;
        y += drawPdfHeader(doc, report.columns, widths, y);
        doc.fontSize(8);
      }

      if (rowIndex % 2 === 1) {
        doc.rect(doc.page.margins.left, y, usableWidth, rowHeight).fill('#F1F5F9');
        doc.fillColor('#000000');
      }

      let x = doc.page.margins.left;

      values.forEach((value, index) => {
        doc.text(value, x + 4, y + 4, { width: widths[index] - 8 });
        x += widths[index];
      });

      y += rowHeight;
    });

    doc.end();
  });
